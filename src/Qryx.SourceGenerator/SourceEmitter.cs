using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Qryx.SourceGenerator;

/// <summary>
/// Formats the generated C# for one <see cref="DtoModel"/>.
/// <para>
/// Native filters are emitted as a per-DTO static <em>query plan</em>: the lambda parameter and every member access
/// node are created once (type initializer), so a request only allocates the comparison nodes and strongly typed
/// parameter holders (<c>QryxParameters.Create&lt;T&gt;</c>: no dictionary lookup, no boxing) and combines all filters
/// into ONE predicate / ONE <c>Where</c>. Plain C# lambdas (<c>x =&gt; x.Age &gt;= v</c>) were ~4x slower because the
/// compiler re-creates the whole expression tree (parameter, member lookups, lambda validation) on every call.
/// </para>
/// </summary>
internal static class SourceEmitter
{
    private const string Queryable = "global::System.Linq.Queryable";
    private const string Builders = "global::Qryx.Expressions.Builders";
    private const string Helper = Builders + ".ExpressionHelper";
    private const string Params = Builders + ".QryxParameters";
    private const string Expr = "global::System.Linq.Expressions.Expression";
    private const string ExprType = "global::System.Linq.Expressions.ExpressionType";
    private const string Options = "global::Qryx.Expressions.Options.QryxOptions";
    private const string RequestInterface = "global::Qryx.Core.Contracts.IQryxRequest";
    private const string RequestException = "global::Qryx.Core.Exceptions.QryxRequestException";
    private const string MaxInCollectionSize = "global::Qryx.Core.Constants.QryxConstants.DefaultMaxInCollectionSize";
    private const string TagWith = "global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.TagWith";
    private const string EntityTypeParameter = "TQryxEntity";

    private static readonly string GeneratorVersion =
        typeof(SourceEmitter).Assembly.GetName().Version?.ToString() ?? "1.0.0";

    public static string Emit(DtoModel model, CompilationFeatures features)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("#nullable enable annotations");
        w.Line("#nullable disable warnings");
        w.Line("#pragma warning disable CS0612, CS0618");
        w.Line();
        w.Line("namespace Qryx.Generated");
        w.Open();
        w.Line("/// <summary>Compile-time generated Qryx query extensions (one partial part per DTO).</summary>");
        w.Line("public static partial class QryxGeneratedExtensions");
        w.Open();

        if (model.EmitKind == DtoEmitKind.Native)
            EmitNative(w, model, features);
        else
            EmitRuntime(w, model, features);

        w.Close();
        w.Close();
        return w.ToString();
    }

    private static void EmitNative(CodeWriter w, DtoModel model, CompilationFeatures features)
    {
        var entity = model.EntityTypeName!;
        var query = $"global::System.Linq.IQueryable<{entity}>";
        var plan = PlanClassName(model);

        w.Line("/// <summary>");
        if (model.Filters.IsEmpty)
        {
            w.Line($"/// Applies the sorting and pagination of <c>{XmlEscape(model.DtoDisplayName)}</c> (it declares no [Filter] properties).");
        }
        else
        {
            w.Line($"/// Applies the [Filter] properties of <c>{XmlEscape(model.DtoDisplayName)}</c> as one parameterized predicate");
            w.Line("/// (pre-built member nodes, typed SQL parameters), then sorting and pagination.");
        }

        w.Line("/// </summary>");
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Qryx.SourceGenerator\", \"{GeneratorVersion}\")]");
        w.Line($"{model.Accessibility} static {query} ApplyGenerated(this {query} query, {model.DtoTypeName} request)");
        w.Open();

        if (!model.IsValueType)
            w.Line("if (request is null) return query;");

        if (!model.Filters.IsEmpty)
        {
            var needsProvider = model.Filters.Any(static f =>
                f.Strategy == FilterStrategy.Runtime ||
                (f.Invariant && f.Operator is FilterOp.StartsWith or FilterOp.EndsWith or FilterOp.Contains));

            if (needsProvider)
                w.Line($"var isPostgreSql = {Helper}.IsPostgreSqlProvider(query.Provider);");

            w.Line($"{Expr}? qryxBody = null;");

            for (int i = 0; i < model.Filters.Count; i++)
            {
                w.Line();
                EmitFilter(w, model.Filters[i], i, entity, plan);
            }

            w.Line();
            w.Line("// All filters -> one Where (one MethodCallExpression / CreateQuery instead of one per filter)");
            w.Line("if (qryxBody is not null)");
            w.Line($"    query = {Queryable}.Where(query, {Expr}.Lambda<global::System.Func<{entity}, bool>>(qryxBody, {plan}.X));");
        }

        EmitTagging(w, model, features);
        EmitSortingAndPagination(w, model, entity);

        w.Line();
        w.Line("return query;");
        w.Close();

        if (!model.Filters.IsEmpty)
        {
            w.Line();
            EmitPlanClass(w, model, plan, entity);
        }
    }

    /// <summary>
    /// Static per-DTO plan: the shared lambda parameter (same instance as the runtime engine, so runtime-delegated
    /// predicate bodies combine directly) and one compiler-validated member node per filter target.
    /// </summary>
    private static void EmitPlanClass(CodeWriter w, DtoModel model, string plan, string entity)
    {
        w.Line($"/// <summary>Pre-built expression nodes for <c>{XmlEscape(model.DtoDisplayName)}</c> (created once).</summary>");
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Qryx.SourceGenerator\", \"{GeneratorVersion}\")]");
        w.Line($"private static class {plan}");
        w.Open();
        w.Line($"internal static readonly global::System.Linq.Expressions.ParameterExpression X = {Builders}.FilterBuilder.EntityParameter<{entity}>();");

        for (int i = 0; i < model.Filters.Count; i++)
        {
            var f = model.Filters[i];
            if (f.Strategy != FilterStrategy.Native)
                continue;

            for (int j = 0; j < f.Targets.Count; j++)
            {
                var node = $"F{i}T{j}";
                w.Line($"internal static readonly {Expr} {node} = {Params}.Member(({entity} x) => x.{f.Targets[j].Access});");

                if (f.Operator is FilterOp.In or FilterOp.NotIn)
                    w.Line($"internal static readonly global::System.Reflection.MethodInfo {node}Contains = {Helper}.GetEnumerableContainsMethod({node}.Type);");
            }
        }

        w.Line();
        w.Line($"internal static {Expr} And({Expr}? left, {Expr} right) => left is null ? right : {Expr}.AndAlso(left, right);");
        w.Close();
    }

    private static void EmitRuntime(CodeWriter w, DtoModel model, CompilationFeatures features)
    {
        var typeParameters = new List<string>();
        var entity = model.EntityTypeName;
        if (entity is null)
        {
            entity = EntityTypeParameter;
            typeParameters.Add(EntityTypeParameter);
        }

        typeParameters.AddRange(model.TypeParameters);

        var query = $"global::System.Linq.IQueryable<{entity}>";
        var typeParameterList = typeParameters.Count > 0 ? "<" + string.Join(", ", typeParameters) + ">" : string.Empty;

        w.Line("/// <summary>");
        w.Line($"/// Applies the [Filter] properties of <c>{XmlEscape(model.DtoDisplayName)}</c> through the runtime engine");
        w.Line("/// (generic DTO or unknown entity type), then sorting and pagination.");
        w.Line("/// </summary>");
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Qryx.SourceGenerator\", \"{GeneratorVersion}\")]");
        w.Line($"{model.Accessibility} static {query} ApplyGenerated{typeParameterList}(this {query} query, {model.DtoTypeName} request)");
        foreach (var clause in model.ConstraintClauses)
            w.Line("    " + clause);
        w.Open();

        if (!model.IsValueType)
            w.Line("if (request is null) return query;");

        w.Line($"query = {Builders}.FilterBuilder.Apply(query, request);");

        EmitTagging(w, model, features);

        if (model.ImplementsRequest && model.EntityTypeName is not null)
        {
            EmitSortingAndPagination(w, model, entity);
        }
        else
        {
            w.Line();
            w.Line($"if ((object)request is {RequestInterface}<{entity}> qryxRequest)");
            w.Open();
            EmitPagingBody(w);
            w.Close();
        }

        w.Line();
        w.Line("return query;");
        w.Close();
    }

    private static void EmitTagging(CodeWriter w, DtoModel model, CompilationFeatures features)
    {
        if (!features.HasEfCoreTagWith)
            return;

        w.Line();
        w.Line($"if ({Options}.EnableQueryTagging)");
        w.Line($"    query = {TagWith}(query, \"Qryx: {StringEscape(model.DtoDisplayName)}\");");
    }

    private static void EmitSortingAndPagination(CodeWriter w, DtoModel model, string entity)
    {
        if (!model.ImplementsRequest)
            return;

        w.Line();
        w.Line($"var qryxRequest = ({RequestInterface}<{entity}>)request;");
        EmitPagingBody(w);
    }

    private static void EmitPagingBody(CodeWriter w)
    {
        w.Line($"var qryxOptions = {Options}.Global;");
        w.Line("if (qryxRequest.AfterCursor is { } afterCursor)");
        w.Open();
        w.Line("// Keyset pagination continues the sortBy ordering (clauses + primary-key tie-breaker) after the cursor.");
        w.Line($"query = {Builders}.PaginationBuilder.ApplyKeyset(query, afterCursor, qryxRequest.PageSize, qryxRequest.SortBy, qryxRequest.IsDescending, request.GetType(), qryxOptions.MaxPageSize);");
        w.Close();
        w.Line("else");
        w.Open();
        w.Line($"query = {Builders}.SortBuilder.Apply(query, qryxRequest, qryxOptions.ThrowOnInvalidSortProperty);");
        w.Line($"query = {Builders}.PaginationBuilder.ApplyOffset(query, qryxRequest.Page, qryxRequest.PageSize, qryxOptions.MaxPageSize);");
        w.Close();
    }

    private static void EmitFilter(CodeWriter w, FilterModel f, int index, string entity, string plan)
    {
        var description = f.Targets.Count > 0
            ? $"{f.PropertyName}: Op.{f.Operator} on {string.Join(" | ", f.Targets.Select(static t => t.Access))}"
            : $"{f.PropertyName}: Op.{f.Operator} (runtime engine)";
        w.Line("// " + description);

        if (f.Strategy == FilterStrategy.Runtime)
        {
            EmitRuntimeFilter(w, f, entity, plan);
            return;
        }

        var value = f.LocalName + "Value";
        var source = "request." + f.PropertyAccess;
        var ctx = new FilterContext(f, index, plan, value);

        switch (f.ValueKind)
        {
            case ValueKind.NullableValue:
            case ValueKind.Reference:
            case ValueKind.Collection:
                w.Line($"if ({source} is {{ }} {value})");
                break;
            case ValueKind.String:
                w.Line($"if ({source} is {{ Length: > 0 }} {value})");
                break;
            case ValueKind.Range when f.IsNullableRange:
                w.Line($"if ({source} is {{ }} {value} && {value}.HasValue)");
                break;
            case ValueKind.Range:
                w.Line($"if ({source} is {{ HasValue: true }} {value})");
                break;
            default:
                w.Open();
                w.Line($"var {value} = {source};");
                EmitNativeBody(w, ctx);
                w.Close();
                return;
        }

        w.Open();
        EmitNativeBody(w, ctx);
        w.Close();
    }

    private static void EmitRuntimeFilter(CodeWriter w, FilterModel f, string entity, string plan)
    {
        // Same lambda parameter as the plan (FilterBuilder.EntityParameter), so the body is AND-ed in directly.
        var predicate = f.LocalName + "Predicate";
        w.Open();
        w.Line($"var {predicate} = {Builders}.FilterBuilder.BuildPropertyPredicate<{entity}>(request, \"{StringEscape(f.PropertyName)}\", isPostgreSql);");
        w.Line($"if ({predicate} is not null) qryxBody = {plan}.And(qryxBody, {predicate}.Body);");
        w.Close();
    }

    /// <summary>Per-filter emission context.</summary>
    private sealed class FilterContext
    {
        private readonly int _index;

        public FilterContext(FilterModel filter, int index, string plan, string value)
        {
            Filter = filter;
            _index = index;
            Plan = plan;
            Value = value;
        }

        public FilterModel Filter { get; }
        public string Plan { get; }
        public string Value { get; }

        public string Node(int target) => $"{Plan}.F{_index}T{target}";

        /// <summary>Typed SQL parameter for the given value, converted to the target column type when needed.</summary>
        public string Param(int target, string valueExpression) =>
            $"{Params}.Create({Cast(Filter.Targets[target], valueExpression)}, {Node(target)}.Type)";

        /// <summary>Condition per target column, combined with OR (index friendly per column).</summary>
        public string AnyTarget(Func<int, string> condition)
        {
            var result = condition(0);
            for (int j = 1; j < Filter.Targets.Count; j++)
                result = $"{Expr}.OrElse({result}, {condition(j)})";
            return result;
        }

        public string AndInto(string expression) => $"qryxBody = {Plan}.And(qryxBody, {expression});";
    }

    private static void EmitNativeBody(CodeWriter w, FilterContext c)
    {
        var f = c.Filter;
        switch (f.Operator)
        {
            case FilterOp.Equals:
                w.Line(c.AndInto(c.AnyTarget(j => $"{Expr}.Equal({c.Node(j)}, {c.Param(j, c.Value)})")));
                break;
            case FilterOp.NotEquals:
                w.Line(c.AndInto(c.AnyTarget(j => $"{Expr}.NotEqual({c.Node(j)}, {c.Param(j, c.Value)})")));
                break;
            case FilterOp.GreaterThan:
            case FilterOp.GreaterThanOrEqual:
            case FilterOp.LessThan:
            case FilterOp.LessThanOrEqual:
                w.Line(c.AndInto(c.AnyTarget(j => Comparison(f.Operator, c.Node(j), c.Param(j, c.Value)))));
                break;
            case FilterOp.StartsWith:
            case FilterOp.EndsWith:
            case FilterOp.Contains:
                EmitStringMatch(w, c);
                break;
            case FilterOp.In:
            case FilterOp.NotIn:
                EmitIn(w, c);
                break;
            case FilterOp.Between:
                EmitBetween(w, c);
                break;
            case FilterOp.IsNull:
            case FilterOp.IsNotNull:
                EmitNullCheck(w, c);
                break;
            default:
                throw new InvalidOperationException($"Operator {f.Operator} has no native emission.");
        }
    }

    private static string Comparison(FilterOp op, string node, string param)
    {
        var type = op switch
        {
            FilterOp.GreaterThan => "GreaterThan",
            FilterOp.GreaterThanOrEqual => "GreaterThanOrEqual",
            FilterOp.LessThan => "LessThan",
            _ => "LessThanOrEqual"
        };

        // ExpressionHelper.BuildComparison also handles relational operators on enum columns
        return $"{Helper}.BuildComparison({ExprType}.{type}, {node}, {param})";
    }

    private static string Cast(TargetModel target, string value) =>
        target.ValueCast is null ? value : $"({target.ValueCast}){value}";

    private static void EmitStringMatch(CodeWriter w, FilterContext c)
    {
        var f = c.Filter;
        var builder = f.Operator switch
        {
            FilterOp.StartsWith => "BuildStartsWith",
            FilterOp.EndsWith => "BuildEndsWith",
            _ => "BuildContains"
        };

        // Same builder as the runtime engine: case-sensitive -> LIKE @p; invariant -> PostgreSQL ILIKE @p ESCAPE '\'
        // (wildcards escaped), other providers UPPER(column) LIKE @p. Value is always a SQL parameter.
        var invariant = f.Invariant ? "true" : "false";
        var postgres = f.Invariant ? "isPostgreSql" : "false";
        w.Line(c.AndInto(c.AnyTarget(j => $"{Helper}.{builder}({c.Node(j)}, {c.Value}, {invariant}, {postgres})")));
    }

    private static void EmitIn(CodeWriter w, FilterContext c)
    {
        var f = c.Filter;
        var name = StringEscape(f.PropertyName);
        var tooMany = $"throw new {RequestException}(\"{name}\", \"'{name}' accepts at most \" + {MaxInCollectionSize} + \" values.\");";

        string list;
        string count;
        switch (f.CollectionKind)
        {
            case CollectionKind.Array:
                list = c.Value;
                count = c.Value + ".Length";
                break;
            case CollectionKind.List:
                list = c.Value;
                count = c.Value + ".Count";
                break;
            default:
                list = f.LocalName + "List";
                count = list + ".Count";
                var item = f.LocalName + "Item";
                w.Line($"var {list} = new global::System.Collections.Generic.List<{f.ElementTypeName}>();");
                w.Line($"foreach (var {item} in {c.Value})");
                w.Open();
                w.Line($"if ({list}.Count == {MaxInCollectionSize}) {tooMany}");
                w.Line($"{list}.Add({item});");
                w.Close();
                break;
        }

        w.Line($"if ({count} > 0)");
        w.Open();
        if (f.CollectionKind != CollectionKind.Enumerable)
            w.Line($"if ({count} > {MaxInCollectionSize}) {tooMany}");

        // One collection parameter shared by all targets: IN (...) / = ANY(@p) via Enumerable.Contains<T>
        var param = f.LocalName + "Param";
        w.Line($"var {param} = {Params}.Create({list});");
        w.Line(c.AndInto(c.AnyTarget(j =>
        {
            var contains = $"{Expr}.Call({c.Node(j)}Contains, {param}, {c.Node(j)})";
            return f.Operator == FilterOp.NotIn ? $"{Expr}.Not({contains})" : contains;
        })));
        w.Close();
    }

    private static void EmitBetween(CodeWriter w, FilterContext c)
    {
        var f = c.Filter;
        var from = f.LocalName + "From";
        var to = f.LocalName + "To";
        var fromOnly = f.LocalName + "FromOnly";
        var toOnly = f.LocalName + "ToOnly";

        // Inclusive bounds, each optional: column >= @from AND column <= @to.
        w.Line($"if ({c.Value}.From is {{ }} {from} && {c.Value}.To is {{ }} {to})");
        w.Line("    " + c.AndInto(c.AnyTarget(j =>
            $"{Expr}.AndAlso({Comparison(FilterOp.GreaterThanOrEqual, c.Node(j), c.Param(j, from))}, {Comparison(FilterOp.LessThanOrEqual, c.Node(j), c.Param(j, to))})")));
        w.Line($"else if ({c.Value}.From is {{ }} {fromOnly})");
        w.Line("    " + c.AndInto(c.AnyTarget(j => Comparison(FilterOp.GreaterThanOrEqual, c.Node(j), c.Param(j, fromOnly)))));
        w.Line($"else if ({c.Value}.To is {{ }} {toOnly})");
        w.Line("    " + c.AndInto(c.AnyTarget(j => Comparison(FilterOp.LessThanOrEqual, c.Node(j), c.Param(j, toOnly)))));
    }

    private static void EmitNullCheck(CodeWriter w, FilterContext c)
    {
        var f = c.Filter;
        var whenTrue = f.Operator == FilterOp.IsNull ? "Equal" : "NotEqual";
        var whenFalse = f.Operator == FilterOp.IsNull ? "NotEqual" : "Equal";

        string Check(string method) =>
            c.AnyTarget(j => $"{Expr}.{method}({c.Node(j)}, {Expr}.Constant(null, {c.Node(j)}.Type))");

        if (!f.IsBooleanValue)
        {
            // Any non-empty, non-boolean value means "true" (same as the runtime engine).
            w.Line(c.AndInto(Check(whenTrue)));
            return;
        }

        w.Line(c.AndInto($"({c.Value} ? {Check(whenTrue)} : {Check(whenFalse)})"));
    }

    /// <summary>
    /// Unique, deterministic nested class name per DTO: sanitized hint name plus an FNV-1a hash of the model key
    /// (string.GetHashCode is randomized per process and would make the generated output non-deterministic).
    /// </summary>
    private static string PlanClassName(DtoModel model)
    {
        var hint = model.HintName.EndsWith(".g.cs", StringComparison.Ordinal)
            ? model.HintName.Substring(0, model.HintName.Length - ".g.cs".Length)
            : model.HintName;

        var sb = new StringBuilder("QryxPlan_", hint.Length + 18);
        foreach (var ch in hint)
            sb.Append(char.IsLetterOrDigit(ch) ? ch : '_');

        uint hash = 2166136261;
        foreach (var ch in model.Key)
        {
            hash ^= ch;
            hash *= 16777619;
        }

        return sb.Append('_').Append(hash.ToString("x8")).ToString();
    }

    private static string XmlEscape(string text) =>
        text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private static string StringEscape(string text) =>
        text.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary>Minimal indented writer.</summary>
    private sealed class CodeWriter
    {
        private readonly StringBuilder _builder = new();
        private int _indent;

        public void Line(string text = "")
        {
            if (text.Length > 0)
                _builder.Append(' ', _indent * 4).Append(text);
            _builder.Append('\n');
        }

        public void Open()
        {
            Line("{");
            _indent++;
        }

        public void Close()
        {
            _indent--;
            Line("}");
        }

        public override string ToString() => _builder.ToString();
    }
}
